import fs from 'node:fs';
import assert from 'node:assert/strict';
import {loadInputs,normalize,reconstruct,seedSql} from '../../scripts/database/model.js';
const input=loadInputs(process.cwd(),['lolita']);
const bundle=normalize(input);
assert.equal(bundle.tables.books.length,1);
bundle.tables.books[0].publication_status='draft';
const rebuilt=reconstruct(bundle,'lolita');
assert.deepEqual(rebuilt.data,input[0].data);
assert.deepEqual(rebuilt.dictionary,input[0].dictionary);
assert.equal(bundle.tables.sections.length,71);
assert.equal(bundle.tables.excerpts.length,0,'Pending quotations must not be serialized as authentic excerpts.');
assert.ok(bundle.tables.place_references.every(r=>r.category==='action'||r.category==='mentioned'));
const dir='database/generated/lolita';fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(dir+'/draft-content.json',JSON.stringify(bundle,null,2)+'\n');
const guard="do $$begin if exists(select 1 from public.books where id='lolita' and publication_status<>'draft') then raise exception 'Refusing to overwrite published Lolita with draft data'; end if; end$$;";
const sql=seedSql(bundle).replace('-- Generated from verified repository datasets. Additive upserts; no deletes.','-- DRAFT ONLY: individual location evidence remains under review. No publication authorization.').replace('set local standard_conforming_strings = on;',()=> 'set local standard_conforming_strings = on;\n'+guard);
fs.writeFileSync(dir+'/content-draft.sql',sql);
fs.writeFileSync(dir+'/draft-roundtrip.json',JSON.stringify({status:'draft',roundTrip:'exact',rows:Object.fromEntries(Object.entries(bundle.tables).map(([k,v])=>[k,v.length])),remoteDatabaseContacted:false},null,2)+'\n');
console.log('PASS: 71-section draft normalized and reconstructed exactly, with four-language introductions and no pending excerpts exposed.');
